export const getConnector = (id: string): ConnectorDefinition | null => CONNECTORS.find(c => c.id === id) || null;

/** Settings stored per connector (routing, mapping, counters). */
export const defaultConnectorSettings = (connector: ConnectorDefinition): ConnectorSettings => ({
  enabled: false,
  project: 'Farm Natura',
  priority: 'High',
  routing: { mode: 'unassigned', salesHead: '', executive: '' },
  duplicates: 'skip',
  mapping: { ...connector.defaultMapping },
  stats: { received: 0, skipped: 0, lastReceivedAt: null }
});

export const DEFAULT_INTEGRATIONS = Object.fromEntries(CONNECTORS.map(c => [c.id, defaultConnectorSettings(c)])) as IntegrationSettings;

/** Merge stored settings over defaults so newly added connectors / fields appear. */
export function hydrateIntegrations(stored: unknown): IntegrationSettings {
  const safe = (stored && typeof stored === 'object' && !Array.isArray(stored) ? stored : {}) as Partial<Record<ConnectorId, Partial<ConnectorSettings>>>;
  return Object.fromEntries(CONNECTORS.map(c => {
    const base = defaultConnectorSettings(c);
    const saved = safe[c.id] || {};
    return [c.id, {
      ...base,
      ...saved,
      routing: { ...base.routing, ...(saved.routing || {}) },
      mapping: { ...base.mapping, ...(saved.mapping || {}) },
      stats: { ...base.stats, ...(saved.stats || {}) }
    }];
  })) as IntegrationSettings;
}

const clean = (v: unknown): string => (typeof v === 'string' ? v.trim() : v == null ? '' : String(v).trim());

/** Platform payload -> CRM fields, joining multiple source fields mapped to one CRM field. */
export function mapPayload(connector: ConnectorDefinition, payload: Submission, mapping: FieldMapping): MappedFields {
  const out: MappedFields = {};
  for (const field of connector.fields) {
    const target = mapping[field.key];
    const value = clean(payload[field.key]);
    if (!target || !value) continue;
    if (target === 'notes') {
      out.notes = [out.notes, `${field.label}: ${value}`].filter(Boolean).join('\n');
    } else {
      out[target] = out[target] ? `${out[target]} ${value}` : value;
    }
  }
  return out;
}

const norm = (v: unknown): string => clean(v).toLowerCase();
const isOpen = (l: Lead): boolean => !l.isJunk && l.status !== 'JUNK' && l.status !== 'Lost' && l.status !== 'Converted';

/** Who a new lead goes to: nobody, the least-loaded executive in a pool, or a fixed executive. */
export function pickAssignee(
  routing: Partial<RoutingRule> | null | undefined,
  { leads, salesExecutives }: { leads: Lead[]; salesExecutives: SalesExecutive[] }
): { salesExecutive: string; salesHead: string } | null {
  if (!routing || routing.mode === 'unassigned') return null;

  if (routing.mode === 'executive') {
    const exec = salesExecutives.find(se => se.name === routing.executive);
    return exec ? { salesExecutive: exec.name, salesHead: exec.reportingSalesHead || '' } : null;
  }

  if (routing.mode === 'balanced') {
    const pool = salesExecutives.filter(se => !routing.salesHead || norm(se.reportingSalesHead) === norm(routing.salesHead));
    if (pool.length === 0) return null;
    const load = (name: string) => leads.filter(l => isOpen(l) && (norm(l.salesExecutive) === norm(name) || norm(l.assignedSalesExecutive) === norm(name))).length;
    const [exec] = [...pool].sort((a, b) => load(a.name) - load(b.name) || a.name.localeCompare(b.name));
    return { salesExecutive: exec.name, salesHead: exec.reportingSalesHead || routing.salesHead || '' };
  }

  return null;
}

const pad = (n: number) => String(n).padStart(2, '0');
const stamp = (d: Date) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`;

/**
 * Run one submission through the pipeline.
 * Returns { lead } to save, { skipped, duplicate } when it's a duplicate to skip,
 * or { error } when the payload can't become a lead.
 */
export function buildIntakeLead({ connectorId, settings, payload, meta = {}, leads, salesExecutives, now = new Date() }: {
  connectorId: string;
  settings: ConnectorSettings;
  payload: Submission;
  meta?: SubmissionMeta;
  leads: Lead[];
  salesExecutives: SalesExecutive[];
  now?: Date;
}): IntakeResult {
  const connector = getConnector(connectorId);
  if (!connector) return { error: `Unknown connector “${connectorId}”.` };

  const fields = mapPayload(connector, payload, settings.mapping);
  if (!fields.leadName) return { error: 'The submission has no name field mapped to “Lead name”.' };
  if (!fields.emailId && !fields.phoneNumber) return { error: 'The submission needs an email or phone number.' };

  const duplicate = findDuplicateLead(leads, { email: fields.emailId, phone: fields.phoneNumber });
  if (duplicate && settings.duplicates === 'skip') return { skipped: true, duplicate };

  const assignee = pickAssignee(settings.routing, { leads, salesExecutives });
  const followup = new Date(now.getTime() + 15 * 60 * 1000); // speed-to-lead: call within 15 minutes

  const lead: Lead = {
    id: `LD-${now.getTime()}`,
    leadName: fields.leadName,
    phoneNumber: fields.phoneNumber || '',
    emailId: fields.emailId || '',
    company: fields.company || 'Not provided',
    designation: fields.designation || '',
    leadSource: connector.source,
    project: settings.project,
    priority: settings.priority,
    status: 'New',
    createdDate: getTodayISO(),
    lastActivity: `Captured from ${connector.name}`,
    nextFollowup: stamp(followup),
    dueToday: true,
    isOverdue: false,
    notes: fields.notes || '',
    nextAction: 'Call within 15 minutes of enquiry',
    intake: {
      connectorId,
      receivedAt: now.toISOString(),
      campaign: meta.campaign || '',
      adSet: meta.adSet || '',
      form: meta.form || '',
      isTest: Boolean(meta.isTest)
    },
    ...(duplicate ? { possibleDuplicateOf: duplicate.id } : {}),
    ...(assignee ? {
      salesExecutive: assignee.salesExecutive,
      assignedSalesExecutive: assignee.salesExecutive,
      leadOwner: assignee.salesExecutive,
      salesHead: assignee.salesHead
    } : { leadOwner: 'Unassigned' })
  };

  return { lead, duplicate };
}

