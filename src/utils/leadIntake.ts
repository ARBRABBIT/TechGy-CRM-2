/** CRM lead field a platform field maps to ('' = don't import). */
export type CrmField = 'leadName' | 'emailId' | 'phoneNumber' | 'company' | 'designation' | 'notes' | '';
export type ConnectorId = 'meta' | 'googleAds' | 'linkedin' | 'webhook' | 'googleMaps';
export type FieldMapping = Record<string, CrmField>;

export interface ConnectorDefinition {
  id: ConnectorId;
  name: string;
  platform: string;
  source: string;
  connectMethod: 'oauth' | 'webhook';
  description: string;
  steps: string[];
  fields: { key: string; label: string }[];
  defaultMapping: FieldMapping;
}

export type RoutingMode = 'unassigned' | 'balanced' | 'executive';

export interface RoutingRule {
  mode: RoutingMode;
  /** Team (sales head name) for balanced routing; '' = all teams */
  salesHead: string;
  /** Executive name for fixed routing */
  executive: string;
}

export interface ConnectorSettings {
  enabled: boolean;
  project: string;
  priority: string;
  routing: RoutingRule;
  duplicates: 'skip' | 'flag';
  mapping: FieldMapping;
  stats: { received: number; skipped: number; lastReceivedAt: string | null };
}

export type IntegrationSettings = Record<ConnectorId, ConnectorSettings>;

/** Raw form submission in the platform's own field names. */
export type Submission = Record<string, unknown>;

export interface SubmissionMeta {
  campaign?: string;
  adSet?: string;
  form?: string;
  isTest?: boolean;
}

type MappedFields = Partial<Record<Exclude<CrmField, ''>, string>>;

export type IntakeResult =
  | { lead: Lead; duplicate: Lead | null; error?: undefined; skipped?: undefined }
  | { skipped: true; duplicate: Lead; lead?: undefined; error?: undefined }
  | { error: string; lead?: undefined; skipped?: undefined; duplicate?: undefined };

