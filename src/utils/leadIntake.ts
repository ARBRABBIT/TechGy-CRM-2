/**
 * Lead intake pipeline shared by every connector (Meta, Google Ads, LinkedIn, webhook).
 *
 * Pure functions: map a platform payload to a CRM lead, check for duplicates and
 * pick an assignee. Today the Integrations page runs it for test leads; once the
 * backend exists, the webhook handlers should run this same code server-side.
 */
